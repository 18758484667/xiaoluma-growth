/* Isolated Chrome profile: never reads the user's game or growth data. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');

(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{const RealDate=Date,fixed=RealDate.parse('2026-10-26T10:00:00+08:00');window.Date=class extends RealDate{constructor(...args){super(...(args.length?args:[fixed]));}static now(){return fixed;}};});
 let passed=0;const ok=(name,condition)=>{assert.ok(condition,name);passed++;console.log('PASS',name);};
 const growth=()=>page.evaluate(()=>JSON.stringify([EVIDENCE_KEY,ASSESSMENT_KEY,OBS_KEY,DX_KEY].map(k=>[k,localStorage.getItem(k)])));
 const filter=(key,val)=>page.locator('#gameFilterPanel button[onclick="setF(this,\''+key+'\',\''+val+'\')"]').click();
 await page.goto('file://'+path.join(__dirname,'..','育儿系统看板.html'));
 await page.locator('#navGames').click();
 ok('游戏库加载且默认当前适龄',await page.locator('#page-games').isVisible()&&await page.locator('#gameGrid .game-card').count()>0&&await page.evaluate(()=>fState.age==='current'));
 ok('只显示一个主游戏卡且不显示独立 variant',await page.evaluate(()=>{const ids=[...document.querySelectorAll('#gameGrid .game-card')].map(x=>x.dataset.activityId);return ids.length===new Set(ids).size;}));
 ok('顶部保留收藏、轻量本周推荐和筛选',await page.locator('.game-library-toolbar button').count()===3);
 ok('高频筛选可见且更多筛选折叠',await page.locator('#gameFilterPanel .game-filter').first().isVisible()&&!(await page.locator('.game-more-inner').isVisible()));
 const before=await growth();
 const first=page.locator('#gameGrid .game-card').first(),id=await first.getAttribute('data-activity-id');
 await first.locator('.library-favorite').click();
 ok('收藏心形即时切换且数量同步',await first.locator('.library-favorite').getAttribute('aria-pressed')==='true'&&await page.locator('#favoriteCount').textContent()==='1');
 await page.locator('#gameFavoritesTab').click();
 ok('我的收藏在原列表筛选',await page.evaluate(()=>fState.favorites)&&await page.locator('#gameGrid .game-card').count()===1);
 await filter('energy','low');
 ok('收藏模式继续保留精力筛选',await page.evaluate(()=>fState.favorites&&fState.energy==='low'));
 await page.locator('#gameFavoritesTab').click();
 ok('返回全部仍保留筛选',await page.evaluate(()=>!fState.favorites&&fState.energy==='low'));
 await filter('location','indoor');await filter('duration','5');await filter('cat','motor');
 ok('领域场景精力时长可组合',await page.evaluate(()=>fState.cat==='motor'&&fState.location==='indoor'&&fState.energy==='low'&&fState.duration==='5'));
 await page.getByRole('button',{name:'清除筛选',exact:true}).click();
 ok('清除筛选恢复当前适龄',await page.evaluate(()=>fState.cat==='all'&&fState.location==='all'&&fState.energy==='all'&&fState.duration==='all'&&fState.age==='current'));
 await page.evaluate(()=>{fState.src='__no_match__';renderGames();});
 ok('无结果显示轻量空状态和清除入口',await page.locator('#gameGrid').textContent().then(t=>t.includes('当前条件下暂时没有合适的游戏'))&&await page.locator('#gameGrid').getByRole('button',{name:'清除部分筛选'}).isVisible());
 await page.locator('#gameGrid').getByRole('button',{name:'清除部分筛选'}).click();
 await page.locator('#gameGrid .game-card[data-activity-id="'+id+'"]').locator('.library-favorite').click();
 ok('取消收藏不写成长数据',await page.locator('#favoriteCount').textContent()==='0'&&await growth()===before);
 await page.locator('#gameFavoritesTab').click();
 ok('收藏空状态有明确提示',await page.locator('#gameGrid').textContent().then(t=>t.includes('还没有收藏游戏')));
 await page.locator('#gameFavoritesTab').click();
 await page.evaluate(()=>{fState.age='all';renderGames();});
 await page.evaluate(()=>openGameDetail('act_117_追泡泡_推行小车'));
 ok('旧 alias 打开同一主游戏详情',await page.locator('.game-detail-head h2').textContent()==='吹泡泡');
 ok('玩法在材料和反馈之前',await page.locator('#gameLibraryDetail').evaluate(el=>{const s=el.textContent;return s.indexOf('怎么玩')<s.indexOf('需要什么')&&s.indexOf('需要什么')<s.indexOf('这次玩得怎么样？');}));
 ok('variant 只在详情出现且可展开',await page.locator('.game-detail-variant').count()>0&&await page.locator('.game-detail-variant').first().click().then(()=>page.locator('.game-detail-variant').first().getAttribute('open')).then(x=>x!==null));
 await page.locator('.game-detail-head .detail-favorite').click();
 ok('详情收藏与列表同一状态',await page.locator('.game-detail-head .detail-favorite').getAttribute('aria-pressed')==='true'&&await page.locator('#favoriteCount').textContent()==='1');
 await page.locator('.game-detail-feedback').getByRole('button',{name:'♥ 很喜欢'}).click();
 ok('孩子反馈沿用原保存路径',await page.evaluate(()=>loadActivityFeedback().some(x=>x.activity_id==='act_14_泡泡追跑'&&x.enjoyment==='love')));
 ok('收藏与反馈互不覆盖',await page.evaluate(()=>isFavoriteActivity('act_14_泡泡追跑')&&loadActivityFeedback().some(x=>x.activity_id==='act_14_泡泡追跑')));
 await page.locator('.game-detail-back').click();
 ok('返回列表保留年龄筛选',await page.evaluate(()=>fState.age==='all')&&await page.locator('#gameGrid').isVisible());
 await page.locator('#gameFavoritesTab').click();await page.locator('#gameGrid .game-card .library-favorite').click();
 ok('收藏列表取消后即时消失',await page.locator('#gameGrid .game-card').count()===0&&await page.locator('#favoriteCount').textContent()==='0');
 await page.locator('#gameFavoritesTab').click();
 const fallback=page.locator('#gameGrid .game-art.is-fallback').first();
 ok('无插画用统一 fallback 且不显示大文字',await fallback.count()>0&&await fallback.textContent().then(t=>t.trim()==='✦'));
 ok('展示和反馈不写成长 evidence',await growth()===before);
 await page.getByRole('button',{name:'清除筛选',exact:true}).click();
 const out=path.join(__dirname,'..','qa-screenshots');fs.mkdirSync(out,{recursive:true});
 for(const [name,width,height] of [['390',390,844],['430',430,932],['desktop',1440,1000]]){
  await page.setViewportSize({width,height});await page.evaluate(()=>window.scrollTo(0,0));
  ok(name+' 列表无横向滚动',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  ok(name+' 列表卡宽度适配',await page.locator('#gameGrid .game-card').first().evaluate(e=>e.getBoundingClientRect().width>140));
  await page.screenshot({path:path.join(out,'game-library-'+name+'.png')});
  await page.evaluate(()=>openGameDetail('act_14_泡泡追跑'));
  ok(name+' 详情无横向滚动',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(out,'game-detail-'+name+'.png')});
  await page.locator('.game-detail-back').click();
 }
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,Math.min(800,document.documentElement.scrollHeight-900)));
 const scrollBefore=await page.evaluate(()=>window.scrollY);
 await page.locator('#gameGrid .game-card').nth(5).locator('.game-card-open').click();
 await page.locator('.game-detail-back').click();
 ok('详情返回恢复列表滚动位置',await page.evaluate(y=>Math.abs(window.scrollY-y)<60,scrollBefore));
 ok('浏览器没有脚本异常',errors.length===0);
 console.log('Game library browser: '+passed+' passed, 0 failed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
